package litrerals;

public class IntegralLiterals {
    int i1 = 10;
    int i2 = 0123;
    int i3 = 0xfaafaa;
    int i4 = 0b1010;
    public static void main(String[] args) {
        IntegralLiterals i = new IntegralLiterals();
        System.out.println(i.i1);
        System.out.println(i.i2);
        System.out.println(i.i3);
        System.out.println(i.i4);
    }
}
